#Um módulo em Python é um arquivo que contém códigos, como funções e variáveis, que podem ser utilizados em outros programas por meio da importação.
#Duas vantagens da modularidade são:
#Organização: o programa fica dividido em partes menores e mais fáceis de entender.
#Reutilização: funções e códigos de um módulo podem ser utilizados em diferentes programas, evitando repetir código.
